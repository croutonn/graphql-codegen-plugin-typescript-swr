import { useMemo } from 'react'
import { createClient } from '../client'
import { getSdkWithHooks } from '../generated/sdk.autogenKey'
import { getSdkWithHooks as getSdkWithHooksA } from '../generated/sdk.keyPrefixA'
import { getSdkWithHooks as getSdkWithHooksB } from '../generated/sdk.keyPrefixB'

const REPO_FULL_NAME = 'octocat/example-repo-2'
const API_A = '/graphql'
const API_B = '/api-b/graphql'

type CommentResult = ReturnType<ReturnType<typeof getSdkWithHooks>['useComment']>

function Panel({ label, result }: { label: string; result: CommentResult }) {
  return (
    <div className="rounded border border-slate-200 p-4">
      <p className="mb-2 font-medium">{label}</p>
      {result.isLoading && <p className="text-slate-500">loading...</p>}
      {result.error && <p className="text-red-600">failed to load: {result.error.message}</p>}
      {result.data?.entry && (
        <>
          <p className="text-sm text-slate-600">description: {result.data.entry.repository.description}</p>
          <p className="text-sm text-slate-600">comments: {result.data.entry.commentCount}</p>
        </>
      )}
    </div>
  )
}

export function KeyPrefixDemo() {
  // Without swrKeyPrefix: both SDKs generate ['Comment', REPO_FULL_NAME], so
  // SWR treats the two APIs' queries as one cache entry.
  const sdkA = useMemo(() => getSdkWithHooks(createClient(undefined, API_A)), [])
  const sdkB = useMemo(() => getSdkWithHooks(createClient(undefined, API_B)), [])
  const collidingA = sdkA.useComment({ repoFullName: REPO_FULL_NAME })
  const collidingB = sdkB.useComment({ repoFullName: REPO_FULL_NAME })

  // With swrKeyPrefix: keys become ['apiA', 'Comment', ...] / ['apiB', 'Comment', ...].
  const prefixedSdkA = useMemo(() => getSdkWithHooksA(createClient(undefined, API_A)), [])
  const prefixedSdkB = useMemo(() => getSdkWithHooksB(createClient(undefined, API_B)), [])
  const prefixedA = prefixedSdkA.useComment({ repoFullName: REPO_FULL_NAME })
  const prefixedB = prefixedSdkB.useComment({ repoFullName: REPO_FULL_NAME })

  return (
    <section className="space-y-6">
      <div>
        <h2 className="text-lg font-semibold text-slate-900">Without swrKeyPrefix: keys collide</h2>
        <p className="text-sm text-slate-500">
          Two APIs (<code>{API_A}</code> and <code>{API_B}</code>) both define a <code>Comment</code> query. Their
          autogenerated keys are identical, so SWR serves both hooks from a single cache entry and the API B panel
          shows API A's data.
        </p>
        <div className="mt-3 grid grid-cols-2 gap-4">
          <Panel label={`API A (${API_A})`} result={collidingA} />
          <Panel label={`API B (${API_B})`} result={collidingB} />
        </div>
      </div>

      <div>
        <h2 className="text-lg font-semibold text-slate-900">With swrKeyPrefix: keys are separated</h2>
        <p className="text-sm text-slate-500">
          Each output file is generated with its own <code>swrKeyPrefix</code> (<code>apiA</code> /{' '}
          <code>apiB</code>), so each hook gets its own cache entry and shows its own API's response.
        </p>
        <div className="mt-3 grid grid-cols-2 gap-4">
          <Panel label={`API A (${API_A})`} result={prefixedA} />
          <Panel label={`API B (${API_B})`} result={prefixedB} />
        </div>
      </div>
    </section>
  )
}
